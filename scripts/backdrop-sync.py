#!/usr/bin/env python3
import sys
import colorsys
import os
import numpy as np
from PIL import Image
from scipy.cluster.vq import kmeans, vq

def rgb_to_hex(rgb):
    return '#{:02x}{:02x}{:02x}'.format(max(0, min(255, int(rgb[0]))), 
                                         max(0, min(255, int(rgb[1]))), 
                                         max(0, min(255, int(rgb[2]))))

def hex_to_rgb(hex_str):
    hex_str = hex_str.lstrip('#')
    return tuple(int(hex_str[i:i+2], 16) for i in (0, 2, 4))

if len(sys.argv) < 4:
    print("Usage: backdrop-sync.py <image-path> <original-wallpaper-path> <output-sh-path>")
    sys.exit(1)

image_path = sys.argv[1]
orig_wallpaper_path = sys.argv[2]
output_path = sys.argv[3]

# Load and resize image to speed up K-Means
img = Image.open(image_path)
img.thumbnail((150, 150))
data = np.asarray(img, dtype=np.float32)
if data.shape[-1] == 4:
    data = data[..., :3]
pixels = data.reshape(-1, 3)

# Run K-Means to find 8 dominant colors
centroids, _ = kmeans(pixels, 8)

# Calculate frequency of each centroid to find the most dominant
code, _ = vq(pixels, centroids)
counts = np.bincount(code)
sorted_indices = np.argsort(counts)[::-1]
sorted_centroids = centroids[sorted_indices]

# Primary dominant color (most frequent)
primary_rgb = sorted_centroids[0]
p_r, p_g, p_b = primary_rgb / 255.0
p_h, p_l, p_s = colorsys.rgb_to_hls(p_r, p_g, p_b)

# Generate background and foreground based on primary hue
# Background: L=6%, S=20%
bg_r, bg_g, bg_b = colorsys.hls_to_rgb(p_h, 0.06, min(p_s, 0.20))
bg_hex = rgb_to_hex((bg_r*255, bg_g*255, bg_b*255))

# Foreground: L=90%, S=15%
fg_r, fg_g, fg_b = colorsys.hls_to_rgb(p_h, 0.90, min(p_s, 0.15))
fg_hex = rgb_to_hex((fg_r*255, fg_g*255, fg_b*255))

# Prepare accent colors from the centroids
# We convert all centroids to HSL, normalize their L and S for readability,
# and sort them by hue.
accents_hsl = []
for c in sorted_centroids:
    r, g, b = c / 255.0
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    # Ensure readability on a dark background: Lightness ~60%, Saturation >= 50%
    l_new = 0.60
    s_new = max(s, 0.50)
    accents_hsl.append((h, l_new, s_new))

# Sort by hue
accents_hsl.sort(key=lambda x: x[0])

# Map to hex colors
accents = []
for h, l, s in accents_hsl:
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    accents.append(rgb_to_hex((r*255, g*255, b*255)))

# If we got fewer than 8 unique centroids, pad it by rotating primary hue
while len(accents) < 8:
    h_new = (p_h + (len(accents) * 0.15)) % 1.0
    r, g, b = colorsys.hls_to_rgb(h_new, 0.60, 0.60)
    accents.append(rgb_to_hex((r*255, g*255, b*255)))

# Background-derived colors (using same hue as primary, but different lightness)
def bg_variant(l_val):
    r, g, b = colorsys.hls_to_rgb(p_h, l_val, min(p_s, 0.20))
    return rgb_to_hex((r*255, g*255, b*255))

color10 = bg_hex
color17 = bg_variant(0.10) # Lualine
color07 = bg_variant(0.13) # Codeblock
color25 = bg_variant(0.16) # Tmux inactive pane
color13 = bg_variant(0.22) # Cursor line
color15 = bg_variant(0.28) # Tmux inactive window

color14 = fg_hex
color16 = rgb_to_hex([c*255 for c in colorsys.hls_to_rgb(p_h, 0.80, min(p_s, 0.30))]) # Selected text

# Muted comments
color09 = rgb_to_hex([c*255 for c in colorsys.hls_to_rgb(p_h, 0.50, min(p_s, 0.15))])

# Accent colors mapping
color01 = accents[0]  # Red/Maroon
color08 = accents[1]  # Peach/Orange/Yellow
color03 = accents[2]  # Green
color06 = accents[3]  # Sapphire/Cyan
color02 = accents[4]  # Blue
color05 = accents[5]  # Lavender
color04 = accents[6]  # Mauve/Purple
# Remaining accent color
remaining_accent = accents[7]

# Spellcheck underlines (red and yellow)
color11 = rgb_to_hex([c*255 for c in colorsys.hls_to_rgb(0.98, 0.55, 0.80)]) # Red
color12 = rgb_to_hex([c*255 for c in colorsys.hls_to_rgb(0.13, 0.55, 0.80)]) # Yellow

# Cursor color: a vibrant accent
color24 = accents[4] # Blue/Cyan accent

# Markdown headings (darkened variants of accents)
def darken_accent(hex_val, l_val=0.18):
    rgb = hex_to_rgb(hex_val)
    r, g, b = [c/255.0 for c in rgb]
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    dr, dg, db = colorsys.hls_to_rgb(h, l_val, s)
    return rgb_to_hex((dr*255, dg*255, db*255))

color18 = darken_accent(color04) # Heading 1
color19 = darken_accent(color02) # Heading 2
color20 = darken_accent(color03) # Heading 3
color21 = darken_accent(color01) # Heading 4
color22 = darken_accent(color05) # Heading 5
color23 = darken_accent(color08) # Heading 6

color26 = color10 # Heading fg

# Write color scheme script
with open(output_path, "w") as f:
    f.write(f"""#!/usr/bin/env bash

# Generated by backdrop-sync
# Wallpaper: {orig_wallpaper_path}

linkarzu_color01="{color01}"
linkarzu_color02="{color02}"
linkarzu_color03="{color03}"
linkarzu_color04="{color04}"
linkarzu_color05="{color05}"
linkarzu_color06="{color06}"
linkarzu_color07="{color07}"
linkarzu_color08="{color08}"
linkarzu_color09="{color09}"
linkarzu_color10="{color10}"
linkarzu_color11="{color11}"
linkarzu_color12="{color12}"
linkarzu_color13="{color13}"
linkarzu_color14="{color14}"
linkarzu_color15="{color15}"
linkarzu_color16="{color16}"
linkarzu_color17="{color17}"
linkarzu_color18="{color18}"
linkarzu_color19="{color19}"
linkarzu_color20="{color20}"
linkarzu_color21="{color21}"
linkarzu_color22="{color22}"
linkarzu_color23="{color23}"
linkarzu_color24="{color24}"
linkarzu_color25="{color25}"
linkarzu_color26="{color26}"

wallpaper="{orig_wallpaper_path}"
""")

# Make the generated script executable
os.chmod(output_path, 0o755)
print(f"Successfully generated colorscheme for {orig_wallpaper_path} at {output_path}")
